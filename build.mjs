// node build.mjs          bundle content/*.json into content.bundle.js (lets index.html run from file://)
// node build.mjs --site   also write the deployable site to _site/
import { readFileSync, writeFileSync, cpSync, rmSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const dir = path.dirname(fileURLToPath(import.meta.url));
const read = f => JSON.parse(readFileSync(path.join(dir, 'content', f), 'utf8'));

export function loadContent() {
  const game = read('game.json');
  return { game, people: read(game.peopleFile), dates: read(game.datesFile) };
}

function site() {
  const out = path.join(dir, '_site');
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out);
  for (const f of ['index.html', 'app.js', 'engine.js', 'style.css', 'content.bundle.js', 'content']) {
    cpSync(path.join(dir, f), path.join(out, f), { recursive: true });
  }
  const skip = src => /(^|\/)(tools|README\.md|\.DS_Store)$|\.test\.js$|\.mjs$/.test(src);
  if (existsSync(path.join(dir, 'people'))) cpSync(path.join(dir, 'people'), path.join(out, 'people'), { recursive: true, filter: src => !skip(src) });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const c = loadContent();
  writeFileSync(path.join(dir, 'content.bundle.js'), `// Generated by build.mjs from content/*.json. Do not edit by hand.\nwindow.FLICK_CONTENT = ${JSON.stringify(c)};\n`);
  console.log(`bundled ${c.people.length} people, ${c.dates.length} dates`);
  if (process.argv.includes('--site')) {
    site();
    console.log('wrote _site/');
  }
}
